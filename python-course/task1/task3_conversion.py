# 1. Convert an integer to a floating-point number.
integer_value = 7
float_value = float(integer_value)
print("1. Integer to float:", float_value, type(float_value))

# 2. Convert a floating-point number to an integer.
float_number = 9.8
int_value = int(float_number)
print("2. Float to integer:", int_value, type(int_value))

# 3. Convert an integer to a string.
string_value = str(integer_value)
print("3. Integer to string:", string_value, type(string_value))

# 4. Convert a string containing a number to an integer.
string_number = "42"
converted_int = int(string_number)
print("4. String to integer:", converted_int, type(converted_int))

# 5. Convert an integer to a Boolean.
boolean_value = bool(integer_value)
print("5. Integer to boolean:", boolean_value, type(boolean_value))
